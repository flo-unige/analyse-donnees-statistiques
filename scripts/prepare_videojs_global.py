"""Wrap the unmodified, vendored Video.js build for use on Quarto pages.

Video.js's UMD distribution normally detects RequireJS and registers an AMD
module. Other scripts on Jupyter pages can leave anonymous AMD definitions
queued, so initialise Video.js independently of that shared module loader.
The wrapper only shadows the three module-detection variables locally.
It does not change window.define, window.require or the original vendor file.
"""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
folder = root / 'cours/session-02/assets/video/vendor/videojs-8.23.8'
source = (folder / 'video.min.js').read_text(encoding='utf-8')
wrapper = ('/* Generated by scripts/prepare_videojs_global.py. Original licence below. */\n'
           '(function (define, module, exports) {\n' + source +
           '\n}).call(window, undefined, undefined, undefined);\n')
(folder / 'video.global.min.js').write_text(wrapper, encoding='utf-8')
